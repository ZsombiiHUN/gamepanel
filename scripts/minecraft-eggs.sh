#!/bin/bash
# Generates GamePanel's own Minecraft eggs (eggs/minecraft/*.json).
#
# The eggs are thin: the work happens in the gamepanel-java images
# (images/java), whose gp-install downloads the server and whose gp-java
# starts it with JVM settings sized for the container. Edit this script, not
# the JSON files, then run it again:
#
#   scripts/minecraft-eggs.sh          write the eggs
#   scripts/minecraft-eggs.sh --check  fail if the committed eggs are stale
set -euo pipefail

cd "$(dirname "$0")/.."
OUT=eggs/minecraft
IMAGE=ghcr.io/zsombiihun/gamepanel-java

# images "25 21 17": the egg's Java images, newest (the default) first.
images() {
	local v
	for v in "$@"; do printf '{"key":"Java %s","value":"%s:%s"}\n' "$v" "$IMAGE" "$v"; done | jq -s from_entries
}

# var NAME ENV DEFAULT RULES DESCRIPTION [hidden]
var() {
	jq -n --arg name "$1" --arg env "$2" --arg def "$3" --arg rules "$4" --arg desc "$5" --arg hidden "${6:-}" '{
		name: $name, description: $desc, env_variable: $env, default_value: $def,
		user_viewable: ($hidden == ""), user_editable: ($hidden == ""), rules: $rules, field_type: "text"
	}'
}

VERSION_RULES='required|string|max:40|regex:/^[A-Za-z0-9][A-Za-z0-9._+-]*$/'
BUILD_RULES='required|string|max:20|regex:/^(latest|[0-9]+)$/'

eula() {
	var "Accept the Minecraft EULA" EULA false 'required|string|in:true,false' \
		"Set to true to accept the Minecraft EULA (https://aka.ms/MinecraftEULA). The server does not start until you do."
}
mc_version() {
	var "Minecraft version" MINECRAFT_VERSION latest "$VERSION_RULES" \
		"\"latest\" or a version such as 1.21.11. Changing it takes effect when you reinstall the server."
}
build() { # project
	var "$1 build" BUILD_NUMBER latest "$BUILD_RULES" \
		"\"latest\" for the newest stable build, or a build number. Takes effect when you reinstall."
}
loader() { # name default description
	var "$1 version" LOADER_VERSION "$2" "$VERSION_RULES" "$3 Takes effect when you reinstall."
}
gc() {
	var "Garbage collector" JVM_GC auto 'required|string|in:auto,g1,zgc' \
		"auto picks G1 with tuned flags, and generational ZGC for heaps of 12 GB or more on Java 21+. Leave it on auto unless you are measuring."
}
extra_flags() {
	var "Extra JVM flags" JVM_EXTRA_FLAGS "" 'nullable|string|max:512' \
		"Added after GamePanel's own flags, so they win. Heap size is set from the server's memory limit; do not add -Xmx."
}
profile() { # server|velocity|bungee
	var "Launch profile" GP_PROFILE "$1" 'required|string|in:server,velocity,bungee' \
		"How gp-java tunes and configures this server." hidden
}

# egg FILE NAME DESCRIPTION KIND STOP DONE IMAGES VARIABLES
egg() {
	jq -n --arg name "$2" --arg desc "$3" --arg kind "$4" --arg stop "$5" --arg ready "$6" \
		--argjson images "$7" --argjson vars "$8" --arg installer "$IMAGE:25" '{
		_comment: "GamePanel Minecraft egg. Generated by scripts/minecraft-eggs.sh; edit that, not this file.",
		meta: {version: "PTDL_v2", update_url: null},
		exported_at: "2026-11-20T00:00:00+00:00",
		name: $name,
		author: "eggs@gamepanel.invalid",
		description: $desc,
		features: ["eula", "java_version", "pid_limit"],
		docker_images: $images,
		file_denylist: [],
		startup: "gp-java",
		config: {
			files: "{}",
			startup: ({done: $ready} | tojson),
			logs: "{}",
			stop: $stop
		},
		scripts: {installation: {
			script: "#!/bin/bash\n# Downloads the server; see images/java/gp-install in the GamePanel repository.\ncd /mnt/server\nexec gp-install \($kind)\n",
			container: $installer,
			entrypoint: "bash"
		}},
		variables: $vars
	}' >"$1"
}

all_java=$(images 25 21 17 11 8)
modern_java=$(images 25 21 17)
server_done=')! For help, type '

gen() {
	local dir=$1
	mkdir -p "$dir"

	egg "$dir/paper.json" "Paper" \
		"High-performance Minecraft server with plugin support (Bukkit/Spigot/Paper). The best default for most servers." \
		paper stop "$server_done" "$all_java" \
		"$(jq -s . <(eula) <(mc_version) <(build Paper) <(gc) <(extra_flags) <(profile server))"

	egg "$dir/purpur.json" "Purpur" \
		"Paper fork with many extra gameplay settings. Runs Paper plugins." \
		purpur stop "$server_done" "$all_java" \
		"$(jq -s . <(eula) <(mc_version) <(build Purpur) <(gc) <(extra_flags) <(profile server))"

	egg "$dir/folia.json" "Folia" \
		"Paper fork that runs regions of the world on separate threads. For large servers with many cores; most plugins do not support it." \
		folia stop "$server_done" "$modern_java" \
		"$(jq -s . <(eula) <(mc_version) <(build Folia) <(gc) <(extra_flags) <(profile server))"

	egg "$dir/vanilla.json" "Vanilla" \
		"The official Minecraft server from Mojang, unmodified." \
		vanilla stop "$server_done" "$all_java" \
		"$(jq -s . <(eula) <(mc_version) <(gc) <(extra_flags) <(profile server))"

	egg "$dir/fabric.json" "Fabric" \
		"Lightweight mod loader. Put mods in the mods folder." \
		fabric stop "$server_done" "$all_java" \
		"$(jq -s . <(eula) <(mc_version) <(loader "Fabric loader" latest "\"latest\" for the newest stable loader, or a version such as 0.16.14.") <(gc) <(extra_flags) <(profile server))"

	egg "$dir/forge.json" "Forge" \
		"The classic mod loader. Put mods in the mods folder." \
		forge stop "$server_done" "$all_java" \
		"$(jq -s . <(eula) <(mc_version) <(loader Forge recommended "\"recommended\", \"latest\", or a Forge version such as 47.4.0.") <(gc) <(extra_flags) <(profile server))"

	egg "$dir/neoforge.json" "NeoForge" \
		"Modern fork of Forge used by most new modpacks (Minecraft 1.20.2 and newer). Put mods in the mods folder." \
		neoforge stop "$server_done" "$modern_java" \
		"$(jq -s . <(eula) <(mc_version) <(loader NeoForge latest "\"latest\" for the newest stable release, or a version such as 21.1.200.") <(gc) <(extra_flags) <(profile server))"

	egg "$dir/velocity.json" "Velocity" \
		"Modern, fast proxy that links several Minecraft servers into one network." \
		velocity shutdown "Done (" "$modern_java" \
		"$(jq -s . \
			<(var "Velocity version" MINECRAFT_VERSION latest "$VERSION_RULES" "\"latest\" or a Velocity version such as 4.3.1. Takes effect when you reinstall.") \
			<(build Velocity) <(extra_flags) <(profile velocity))"

	egg "$dir/bungeecord.json" "BungeeCord" \
		"The original Minecraft proxy. Prefer Velocity for new networks; use this for BungeeCord-only plugins. Reinstall to update." \
		bungeecord end "Listening on " "$modern_java" \
		"$(jq -s . <(extra_flags) <(profile bungee))"
}

if [ "${1:-}" = --check ]; then
	tmp=$(mktemp -d)
	trap 'rm -rf "$tmp"' EXIT
	gen "$tmp"
	diff -r "$tmp" "$OUT" || { echo "eggs/minecraft is stale: run scripts/minecraft-eggs.sh" >&2; exit 1; }
else
	gen "$OUT"
fi
